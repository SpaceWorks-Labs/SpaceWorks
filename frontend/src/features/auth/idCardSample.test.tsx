/// <reference types="node" />
import { render } from "@testing-library/react";
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { AuthShowcase } from "./AuthShowcase";
import { SampleIdCard } from "./SampleIdCard";
import { STAFF_TOKENS, patternProblem, renderPattern } from "../../components/card-designer/numberPattern";
import { SAMPLE_LOOK, SAMPLE_NUMBER_PATTERN, SAMPLE_NUMBER_PREFIX, SAMPLE_PHOTO, sampleHolder, sampleIdCardFront } from "./idCardSample";

const templates = "../backend/apps/card_designs/default_templates";

describe("sample staff ID card", () => {
  it("is the real generator's staff card (Aurora look) from the checked-in fixture", () => {
    const layers = sampleIdCardFront().layers;
    const at = (name: string) => layers.find(layer => layer.name === name)!;
    // The look and the staff post-processing come from the Python source, not a hand copy.
    const look = readFileSync(`${templates}/__init__.py`, "utf8");
    expect(look).toContain('"aurora": "Aurora"');
    expect(SAMPLE_LOOK).toBe("aurora");
    const aurora = readFileSync(`${templates}/fronts_org.py`, "utf8").split("def aurora(domain, theme):")[1].split("def kasavu")[0];
    expect(aurora).toContain('.photo(5, 15, 18, 22)');
    expect(aurora).toContain('.qr(_code(domain), 63.3, 17, 19)');
    expect([at("Photo").x_mm, at("Photo").y_mm, at("Photo").w_mm, at("Photo").h_mm]).toEqual([5, 15, 18, 22]);
    expect([at("Check QR").x_mm, at("Check QR").y_mm, at("Check QR").w_mm]).toEqual([63.3, 17, 19]);
    // staff.py: a desk QR becomes the check QR, plan shows roles, plus the STAFF band.
    const staff = readFileSync(`${templates}/staff.py`, "utf8");
    expect(staff).toContain("BAND_HEIGHT = 3.4");
    expect(layers.some(layer => layer.kind === "desk_qr")).toBe(false);
    expect(layers.filter(layer => layer.kind === "data_field").map(layer => layer.field)).toEqual(["name", "number", "valid_until", "roles"]);
    expect(at("Staff band").y_mm).toBeCloseTo(53.98 - 3.4);
    expect(at("Space logo").kind).toBe("logo");
    // The number is generated by the engine's numbering grammar with the owner's sample scheme (306 addendum 2).
    expect(patternProblem(SAMPLE_NUMBER_PREFIX, SAMPLE_NUMBER_PATTERN, STAFF_TOKENS)).toBeNull();
    expect(renderPattern(SAMPLE_NUMBER_PATTERN, SAMPLE_NUMBER_PREFIX, 7)).toBe("TNK-STF-0007");
  });

  it("carries the owner's sample holder and his optimised avatar", () => {
    expect(sampleHolder()).toMatchObject({ name: "Shaan Shoukath", roles: "Systems Engineer", space: "Tinkerspace", organisation: "SpaceWorks Labs" });
    expect(SAMPLE_PHOTO).toBe("/brand/sample/shaan-shoukath.webp");
    const bytes = readFileSync(`public${SAMPLE_PHOTO}`);
    expect(bytes.subarray(8, 12).toString("ascii")).toBe("WEBP");
    expect(bytes.length).toBeLessThanOrEqual(40 * 1024);
  });

  it("renders through the card renderer as a decorative picture", () => {
    const { container } = render(<SampleIdCard width={340} />);
    const card = container.querySelector("[data-sample-id-card]")!;
    expect(card).toHaveAttribute("aria-hidden", "true");
    expect(card).toHaveTextContent("Shaan Shoukath");
    expect(card).toHaveTextContent("Systems Engineer");
    expect(card).toHaveTextContent("SpaceWorks Labs");
    expect(card).toHaveTextContent("TNK-STF-0007");
    expect(card.querySelector(`img[src="${SAMPLE_PHOTO}"]`)).not.toBeNull();
    expect(card.querySelectorAll("a, button, input")).toHaveLength(0);
  });

  it("is what the sign-in screens show in their showcase", () => {
    const { container } = render(<AuthShowcase />);
    expect(container.querySelector("[data-sample-id-card]")).toHaveTextContent("Tinkerspace");
  });
});
