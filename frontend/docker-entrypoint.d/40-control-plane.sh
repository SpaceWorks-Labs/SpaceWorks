#!/bin/sh
set -eu

fail() {
  echo "Invalid control-plane config: $1" >&2
  exit 1
}

snippet="${CONTROL_PLANE_SNIPPET:-/etc/nginx/spaceworks.d/control-plane.conf}"
case "${CONTROL_PLANE_PROXY-false}" in
  false) rm -f "$snippet"; exit 0 ;;
  true) ;;
  *) fail 'CONTROL_PLANE_PROXY must be true or false' ;;
esac

. "${CONTROL_PLANE_LIB:-/usr/local/lib/spaceworks/control-plane-allowlist.sh}"
cidrs="${CONTROL_PLANE_ALLOW_CIDRS:-}"
if [ -n "$cidrs" ]; then
  cp_valid_cidr_list "$cidrs" || fail 'CONTROL_PLANE_ALLOW_CIDRS must contain 1-32 valid IP addresses or CIDRs separated by single spaces'
fi

upstream="${CONTROL_PLANE_UPSTREAM:-http://backend:8000}"
case "$upstream" in
  http://*) authority="${upstream#http://}" ;;
  *) fail 'CONTROL_PLANE_UPSTREAM must be http://hostname:port' ;;
esac
host="${authority%:*}"; port="${authority##*:}"
case "$host" in ''|*[!A-Za-z0-9.-]*) fail 'CONTROL_PLANE_UPSTREAM must be http://hostname:port' ;; esac
case "$port" in ''|*[!0-9]*) fail 'CONTROL_PLANE_UPSTREAM must be http://hostname:port' ;; esac
[ "$authority" = "$host:$port" ] || fail 'CONTROL_PLANE_UPSTREAM must be http://hostname:port'
proto="${CONTROL_PLANE_PROTO-\$external_scheme}"
case "$proto" in
  '$external_scheme'|'$scheme') ;;
  *) fail 'CONTROL_PLANE_PROTO must be $external_scheme or $scheme' ;;
esac

mkdir -p "$(dirname "$snippet")"
temporary="$(mktemp "$snippet.XXXXXX")"
trap 'rm -f "$temporary"' EXIT
trap 'exit 1' HUP INT TERM
{
  echo '# Generated by 40-control-plane.sh from CONTROL_PLANE_PROXY / CONTROL_PLANE_ALLOW_CIDRS.'
  echo 'location ~ ^/(control(/|$)|mfa/control/) {'
  if [ -n "$cidrs" ]; then
    for cidr in $cidrs; do printf '    allow %s;\n' "$cidr"; done
    echo '    deny all;'
  fi
  printf '    proxy_pass %s;\n' "$upstream"
  echo '    proxy_set_header Host $http_host;'
  echo '    proxy_set_header X-Real-IP $remote_addr;'
  echo '    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;'
  printf '    proxy_set_header X-Forwarded-Proto %s;\n' "$proto"
  echo '}'
} > "$temporary"
mv -f "$temporary" "$snippet"
