// Generates src/generated/locales.ts from the one authored locale registry,
// backend/config/supported_locales.json, so the two stacks can never list different
// locales. The output is committed: the frontend Docker build context is frontend/ and
// cannot read backend/. Rerun after editing the registry: `npm run generate:locales`.
import fs from "node:fs/promises";
import { pathToFileURL } from "node:url";

const registry = new URL("../../backend/config/supported_locales.json", import.meta.url);
const output = process.env.LOCALES_OUTPUT
  ? pathToFileURL(process.env.LOCALES_OUTPUT)
  : new URL("../src/generated/locales.ts", import.meta.url);
const CODE = /^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/;

const entries = JSON.parse(await fs.readFile(registry, "utf8"));
if (!Array.isArray(entries) || entries.length === 0) throw new Error("Locale registry is empty.");
for (const entry of entries) {
  if (!CODE.test(entry?.code ?? "") || typeof entry.label !== "string" || !entry.label.trim()) {
    throw new Error(`Invalid locale registry entry: ${JSON.stringify(entry)}`);
  }
}
if (entries[0].code !== "en") throw new Error("The system locale en must be listed first.");

const body = `// Generated by scripts/generate-locales.mjs from backend/config/supported_locales.json.
// Do not edit by hand.

// i18n-ignore: each label is that language's own name, shown untranslated in the switcher.
export const SUPPORTED_LOCALES = ${JSON.stringify(entries.map(({ code, label }) => ({ code, label })))} as const;

export type LocaleCode = (typeof SUPPORTED_LOCALES)[number]["code"];

export const SYSTEM_LOCALE: LocaleCode = "en";
`;
await fs.writeFile(output, body);
