// Regenerates the registry-derived data behind /features/<module> from the BACKEND SOURCES (no Python, no database,
// nothing outside this repo):
//   catalogue/registryData.ts    per-module reports, Metabase views and Grafana dashboards
//   catalogue/registryTitles.ts  human titles for them (t literals, so Lingui can extract them)
//   catalogue/limitData.ts       per-module limit keys (apps/makerspaces/limit_modules.py KEY_MODULE)
//
//   npm run features:catalogue            rewrite the three files
//   npm run features:catalogue -- --check fail (exit 1) if they differ from what the backend says now
//
// Reports: apps/operations/report_coverage.py (replayed by coverage.mjs) and report_definitions*.py (titles).
// Analytics: apps/analytics/catalogue/*.py View(...) calls and apps/analytics/grafana_dashboards.py.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { evaluateCoverage } from "./coverage.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, "../..");
const apps = path.resolve(frontend, "../backend/apps");
const out = path.resolve(frontend, "src/features/hub/featuresPage/catalogue");
const read = file => readFileSync(file, "utf8");
const pyFiles = dir => readdirSync(dir).filter(name => name.endsWith(".py")).sort().map(name => path.join(dir, name));

const HEADER = "GENERATED by frontend/scripts/features-catalogue/generate.mjs (npm run features:catalogue). Do not edit by hand.";
const sentence = key => {
  const words = key.replace(/[-_]/g, " ").trim();
  return (words.charAt(0).toUpperCase() + words.slice(1)).replace(/\bqr\b/gi, "QR").replace(/\bsms\b/gi, "SMS");
};
const esc = text => text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

function moduleKeys() {
  const keys = [];
  for (const file of pyFiles(`${apps}/makerspaces`).filter(name => /module_registry_\w+\.py$/.test(name))) {
    for (const chunk of read(file).split("ModuleDefinition(").slice(1)) {
      const key = /^\s*"(\w+)"/.exec(chunk)?.[1];
      if (key && /group=GROUP_/.test(chunk)) keys.push(key);
    }
  }
  return keys;
}

function reportTitles(keys) {
  const files = pyFiles(`${apps}/operations`).filter(name => /report/.test(path.basename(name))).map(name => [name, read(name)]);
  const titles = {};
  for (const key of keys) {
    for (const [, text] of files) {
      const at = text.search(new RegExp(`\\(\\s*"${key}"\\s*,`));
      if (at < 0) continue;
      const rest = text.slice(at + 1);
      const next = rest.search(/\n\s*(?:_?\w+|ReportDefinition)\(\s*"[a-z0-9-]+"\s*,/);
      const chunk = text.slice(at, at + 1 + (next < 0 ? 900 : Math.min(next, 900)));
      const match = /title=(?:gettext_noop|_|gettext)\(\s*"([^"]+)"/.exec(chunk) ?? /gettext_noop\(\s*"([^"]+)"/.exec(chunk);
      if (match) { titles[key] = match[1]; break; }
    }
  }
  return titles;
}

const DOMAIN_MODULE = { inventory: "public_inventory", machines: "machines", bookings: "bookings", events: "events", tickets: "events",
  membership: "membership", payments: "payments", procurement: "public_inventory", donations: "payments", shop: "shop" };

function analyticsViews(modules) {
  const views = {};
  for (const file of pyFiles(`${apps}/analytics/catalogue`).filter(name => !/(registry|types|render)\.py$/.test(name))) {
    const text = read(file);
    const constants = Object.fromEntries([...text.matchAll(/^(\w+) = "(\w+)"$/gm)].map(match => [match[1], match[2]]));
    for (const chunk of text.split(/\bView\(/).slice(1)) {
      const call = /^\s*"(\w+)",\s*("?\w+"?)/.exec(chunk);
      if (!call) continue;
      const domain = call[2].startsWith('"') ? call[2].slice(1, -1) : constants[call[2]] ?? call[2];
      const requires = /requires=\(\s*"(\w+)[."]/.exec(chunk.split(/\n {4}View\(|\n\)/)[0])?.[1];
      const module = modules.has(requires) ? requires : DOMAIN_MODULE[domain];
      if (module && modules.has(module)) (views[module] ??= []).push(call[1]);
    }
  }
  return views;
}

function grafanaDashboards(modules) {
  const text = read(`${apps}/analytics/grafana_dashboards.py`);
  const map = /MODULE = \{([\s\S]*?)\}/.exec(text)[1];
  const boards = {};
  for (const [, area, module] of map.matchAll(/"(\w+)": "(\w+)"/g)) if (modules.has(module)) (boards[module] ??= []).push(area);
  return boards;
}

export function build() {
  const modules = moduleKeys();
  const moduleSet = new Set(modules);
  const { coverage, unparsed } = evaluateCoverage(apps);
  const views = analyticsViews(moduleSet);
  const boards = grafanaDashboards(moduleSet);
  const rows = Object.fromEntries(modules.map(module => [module, {
    reports: (coverage[module] ?? []).filter(key => key !== "module-operational-health"),
    views: views[module] ?? [], dashboards: boards[module] ?? [],
  }]));
  const reportKeys = [...new Set(Object.values(rows).flatMap(row => row.reports))].sort();
  const viewNames = [...new Set(Object.values(rows).flatMap(row => row.views))].sort();
  const boardNames = [...new Set(Object.values(rows).flatMap(row => row.dashboards))].sort();
  const titles = reportTitles(reportKeys);

  const registryData = `// ${HEADER}
// Source: apps/operations/report_coverage.py (+ the replayed loops), apps/analytics/catalogue/*.py, grafana_dashboards.py.
// registry.test.ts and freshness.test.ts fail when this drifts from the backend.
export type RegistryRow = { reports: string[]; views: string[]; dashboards: string[] };
export const REGISTRY: Record<string, RegistryRow> = {
${Object.entries(rows).map(([module, row]) => `  ${module}: { reports: ${JSON.stringify(row.reports)}, views: ${JSON.stringify(row.views)}, dashboards: ${JSON.stringify(row.dashboards)} },`).join("\n")}
};
`;
  const cases = (list, title) => list.map(key => `    case ${JSON.stringify(key)}: return t\`${esc(title(key))}\`;`).join("\n");
  const registryTitles = `import { t } from "@lingui/core/macro";

// ${HEADER}
// Titles are the report definitions' own \`title\`, or the key in sentence case where the definition derives it
// (\`key.replace("-", " ").title()\`); Metabase views and Grafana dashboards are named from their ids.
export function reportTitle(key: string): string {
  switch (key) {
${cases(reportKeys, key => titles[key] ?? sentence(key))}
    default: return key;
  }
}

export function viewTitle(name: string): string {
  switch (name) {
${cases(viewNames, sentence)}
    default: return name;
  }
}

export function dashboardTitle(name: string): string {
  switch (name) {
${cases(boardNames, name => `${sentence(name)} dashboard`)}
    default: return name;
  }
}
`;
  const limits = read(`${apps}/makerspaces/limit_modules.py`);
  const keyModule = limits.slice(limits.indexOf("KEY_MODULE = {"), limits.indexOf("MODULE_EXEMPT = {"));
  const byModule = {};
  for (const [, key, module] of keyModule.matchAll(/"(\w+)": "(\w+)"/g)) (byModule[module] ??= []).push(key);
  const limitData = `// ${HEADER}
// Source: apps/makerspaces/limit_modules.py KEY_MODULE (decision 328 a). Display names come from the console's own
// limitLabel (features/staff/platformSpaces/limitCopy.ts).
export const MODULE_LIMIT_KEYS: Record<string, string[]> = {
${Object.entries(byModule).map(([module, keys]) => `  ${module}: ${JSON.stringify(keys)},`).join("\n")}
};
`;
  return { files: { "registryData.ts": registryData, "registryTitles.ts": registryTitles, "limitData.ts": limitData }, unparsed };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { files, unparsed } = build();
  const check = process.argv.includes("--check");
  let bad = unparsed.length > 0;
  if (unparsed.length) console.error(`report_coverage.py has statements coverage.mjs does not replay:\n  ${unparsed.join("\n  ")}`);
  for (const [name, body] of Object.entries(files)) {
    const file = path.join(out, name);
    if (check) {
      if (read(file).replace(/\r\n/g, "\n") !== body) { bad = true; console.error(`${name} is out of date: run npm run features:catalogue`); }
    } else writeFileSync(file, body);
  }
  if (!check) console.log(`wrote ${Object.keys(files).join(", ")}`);
  process.exit(bad ? 1 : 0);
}
