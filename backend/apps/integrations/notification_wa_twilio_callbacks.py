"""Authenticate all form fields before interpreting proof, STOP or delivery state."""
import base64
import hashlib
import hmac
import re

from django.utils.crypto import salted_hmac

from apps.accounts import rbac
from .models_contract import NotificationDelivery
from .notification_providers import CallbackEvent, EndpointProof
from .notification_wa_twilio_config import ConfigurationError, callback_path, phone, sid

# Twilio also reports accepted/sending (Messaging Service) and canceled; an unmapped
# but correctly signed status would otherwise be answered 403 and alarm the debugger.
STATES = {"accepted": "accepted", "queued": "accepted", "sending": "accepted", "sent": "sent",
          "delivered": "delivered", "read": "read", "failed": "failed", "undelivered": "failed",
          "canceled": "failed"}
SINGLE_FIELDS = {"AccountSid", "MessageSid", "MessageStatus", "SmsStatus", "From", "To", "Body", "MessagingServiceSid"}


def authenticated_form(config, credentials, request):
    # DRF's content_type is the raw header; Twilio may append "; charset=utf-8".
    media_type = (request.content_type or "").split(";", 1)[0].strip().lower()
    if request.method != "POST" or media_type != "application/x-www-form-urlencoded":
        return None
    signature = request.headers.get("X-Twilio-Signature", "")
    if not signature.isascii() or len(signature) > 128 or len(request.body) > 16384:
        return None
    params = request.POST
    if len(params) > 100 or any(len(k) > 128 or any(len(v) > 8192 for v in params.getlist(k)) for k in params):
        return None
    # Twilio's validator sorts keys and each key's distinct values. Include unknown
    # parameters too, so new upstream fields do not weaken signature coverage.
    material = credentials.public_base_url + request.get_full_path()
    for key in sorted(params):
        for value in sorted(set(params.getlist(key))):
            material += key + value
    expected = base64.b64encode(hmac.new(credentials.auth_token.encode(), material.encode(), hashlib.sha1).digest()).decode()
    if not hmac.compare_digest(expected, signature):
        return None
    if any(len(params.getlist(key)) != 1 for key in SINGLE_FIELDS if key in params):
        return None
    if params.get("AccountSid") != credentials.account_sid:
        return None
    message_sid = params.get("MessageSid", "")
    if not sid(message_sid, "SM") and not sid(message_sid, "MM"):
        return None
    return params


def _business_matches(credentials, params, field):
    if credentials.sender:
        return params.get(field) == "whatsapp:" + credentials.sender
    # A service-only installation must also prove which business received/sent it.
    return params.get("MessagingServiceSid") == credentials.messaging_service_sid


def verify_callback(config, credentials, request):
    params = authenticated_form(config, credentials, request)
    if params is None:
        return None
    path = request.path
    if path == callback_path(config, "inbound"):
        if not _business_matches(credentials, params, "To"):
            return None
        try:
            if not params.get("From", "").startswith("whatsapp:"):
                return None
            sender = phone(params["From"])
        except ConfigurationError:
            return None
        digest = salted_hmac("notification.endpoint.identity.v1",
            f"{config.pk}:{config.generation}:{sender}", algorithm="sha256").hexdigest()
        body = params.get("Body", "").strip()
        if body.upper() in {"STOP", "UNSUBSCRIBE"}:
            return CallbackEvent(identity_digest=digest, opt_out=True, inbound=True)
        if body.upper() in {"START", "UNSTOP", "YES"}:
            return CallbackEvent(identity_digest=digest, opt_in=True, inbound=True)
        # The challenge code is generated by token_urlsafe(32); accept exactly that
        # opaque reply, never infer an account from a phone number alone.
        if re.fullmatch(r"[A-Za-z0-9_-]{43}", body):
            return CallbackEvent(proof=EndpointProof(body, sender, config.integration_identity,
                sender, private=True), inbound=True)
        return CallbackEvent(identity_digest=digest, inbound=True)
    match = re.search(r"/status/([1-9][0-9]*)$", path)
    if not match or path != callback_path(config, "status", int(match[1])):
        return None
    state = STATES.get(params.get("MessageStatus", params.get("SmsStatus", "")))
    if not state or not _business_matches(credentials, params, "From"):
        return None
    delivery = rbac.scope_notification_policy(NotificationDelivery.objects.all(),
        makerspace_id=config.makerspace_id).select_related("endpoint").filter(pk=int(match[1]),
        channel="whatsapp", provider="twilio", integration_generation=config.generation,
        integration_identity=config.integration_identity, endpoint__configuration=config).first()
    if not delivery or not delivery.endpoint or (delivery.provider_id and delivery.provider_id != params["MessageSid"]):
        return None
    if params.get("To") != "whatsapp:" + phone(delivery.endpoint.destination):
        return None
    return CallbackEvent(provider_id=params["MessageSid"], state=state, delivery_id=delivery.pk)
